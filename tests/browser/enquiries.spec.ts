import { test, expect } from '@playwright/test';
import { randomUUID } from 'node:crypto';

test('durable enquiry, truthful receipt, duplicate protection and Admin-only inbox', async ({ browser, page, request }, info) => {
  test.skip(info.project.name !== 'desktop');
  // This flow hydrates two fresh native CMS sessions as well as exercising intake.
  test.setTimeout(60_000);
  const admin = await browser.newContext({ baseURL: 'http://127.0.0.1:4372', storageState: '.superpowers/admin-state.json' });
  const editor = await browser.newContext({ baseURL: 'http://127.0.0.1:4372', storageState: '.superpowers/editor-state.json' });
  const route = '/_emdash/api/plugins/surfactants-enquiries';
  const headers = { Origin: 'http://127.0.0.1:4372' };
  const identity = randomUUID();
  const body = { firstName: 'Grace', lastName: 'Fixture', company: 'Test Laboratory', country: 'Malaysia', email: 'grace@example.test', message: 'Please send more information about your surfactants.', consent: true, consentText: 'I agree that KLK OLEO may use my submitted details to respond to this enquiry.', idempotencyKey: identity };
  const stored = await request.post(`${route}/submit`, { headers, data: body });
  expect(stored.status()).toBe(202);
  expect((await stored.json()).receipt).toBe(identity);
  expect((await request.post(`${route}/submit`, { headers, data: body })).status()).toBe(202);
  expect((await request.post(`${route}/submit`, { headers, data: { ...body, message: 'A changed enquiry message.' } })).status()).toBe(409);
  expect((await request.post(`${route}/submit`, { headers: { Origin: 'https://outside.example' }, data: { ...body, idempotencyKey: randomUUID() } })).status()).toBe(403);
  expect((await request.post(`${route}/submit`, { headers, data: { ...body, message: 'x'.repeat(21_000) } })).status()).toBe(413);
  expect((await request.get(`${route}/list`)).status()).toBe(401);
  expect((await editor.request.get(`${route}/list`,{headers:{'X-EmDash-Request':'1'}})).status()).toBe(403);
  const inbox = await admin.request.get(`${route}/list`,{headers:{'X-EmDash-Request':'1'}});
  expect(inbox.headers()['cache-control']).toContain('private');
  expect(inbox.ok(),await inbox.text()).toBe(true);
  const leads = (await inbox.json()).data.items;
  expect(leads.filter((item: { id: string }) => item.id === identity)).toHaveLength(1);
  expect(leads[0].data.consentText).toBe(body.consentText);
  expect(leads[0].data.notificationStatus).toBe('not-configured');
  expect(leads[0].data.notificationPreview.text).toContain('grace@example.test');
  await page.goto(`/surfactants/thank-you?receipt=${identity}`);
  await expect(page.getByRole('heading', { name: 'Thank you for your enquiry' })).toBeVisible();
  await page.goto(`/surfactants/thank-you?receipt=${randomUUID()}`);
  await expect(page.getByRole('heading', { name: 'Enquiry receipt unavailable' })).toBeVisible();
  const adminPage = await admin.newPage();
  await adminPage.goto('/_emdash/admin/');
  await adminPage.getByRole('button',{name:'Get Started',exact:true}).click();
  await adminPage.getByRole('link',{name:'Enquiries',exact:true}).click();
  await expect(adminPage.getByRole('heading', { name: 'Surfactants enquiries' })).toBeVisible();
  await expect(adminPage.getByText('grace@example.test', { exact: true })).toBeVisible();
  await adminPage.screenshot({ path: '.superpowers/parity/admin-inbox.png', fullPage: true });
  const editorPage = await editor.newPage();
  await editorPage.goto('/_emdash/admin/');
  await editorPage.getByRole('button',{name:'Get Started',exact:true}).click();
  await editorPage.goto('/_emdash/admin/plugins/surfactants-enquiries/inbox');
  await expect(editorPage.getByText('Agency administration is required to access enquiries.')).toBeVisible();
  await expect(editorPage.getByText('grace@example.test', { exact: true })).toHaveCount(0);
  await admin.close(); await editor.close();
});

test('contact form sends only after review and redirects to a verified receipt', async ({ page }) => {
  await page.goto('/surfactants/contact?product=PALMOSALT');
  await page.getByLabel('First Name').fill('Ada'); await page.getByLabel('Last Name').fill('Browser');
  await page.getByLabel('Company Name').fill('Test Company'); await page.getByLabel('Country').selectOption({ label: 'Malaysia' });
  await page.getByLabel('Email', { exact: false }).fill('ada@example.test'); await page.locator('input[name=consent]').check();
  await page.getByRole('button', { name: 'Review enquiry' }).click();
  await expect(page.getByRole('heading', { name: 'Review your enquiry' })).toBeVisible();
  await page.getByRole('button', { name: 'Send enquiry', exact: true }).click();
  await expect(page).toHaveURL(/\/surfactants\/thank-you\?receipt=/);
  await expect(page.getByRole('heading', { name: 'Thank you for your enquiry' })).toBeVisible();
});
